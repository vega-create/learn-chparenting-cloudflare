import { MetadataRoute } from "next";
import { getAllSlugs } from "@/lib/blog";
import CONTENT_DATES from "@/data/content-dates.json";

const BASE = process.env.NEXT_PUBLIC_SITE_URL || "https://learn.chparenting.com";

/**
 * 2026-11 起 sitemap 只列「要進索引的頁」。
 *
 * 之前 362 頁全列，Google 把其中 300 多頁放進「已檢索 - 目前尚未建立索引」：
 * 練習模式頁（game／speaking／mock-test／writing）、單一桌遊頁、科目的子分類頁
 * 對搜尋者來說內容都在互動區，初始 HTML 很薄；八個級別的 unit 頁又是同一套模板句。
 *
 * 現在的做法（與各頁 robots 設定對齊）：
 *   - 只列：首頁、平台頁、8 個級別總覽、8 個家長指南總覽、6 個科目首頁、全部 blog 文章、
 *     以及「老師的話」已擴寫成單元專屬內容的級別的 unit 頁（目前只有 GEPT 初級）。
 *   - 其他 unit 頁、練習模式頁、桌遊頁等已加 noindex+follow（見 lib/seo.ts 與各 layout），
 *     頁面與網址都還在，選單與內部連結照舊，改好一個級別就把那個級別加回來。
 *   - INDEXED_UNIT_LEVELS 要和 lib/unit-seo.ts 的 unitPagesIndexable 一致。
 */

// Real per-page content dates, regenerated by scripts/generate-content-dates.mjs
// on every build. Emitting `new Date()` here instead would stamp all URLs
// with one build time, which Google discards as an unreliable lastmod.
const DATES = CONTENT_DATES as Record<string, string>;
const FALLBACK = new Date("2026-03-05T00:00:00Z");

function lm(routePath: string): Date {
  const iso = DATES[routePath];
  return iso ? new Date(iso) : FALLBACK;
}

/** Sitemap entry for a route path (e.g. "/elementary/unit/3"). */
function entry(
  routePath: string,
  changeFrequency: MetadataRoute.Sitemap[number]["changeFrequency"],
  priority: number,
) {
  return {
    url: routePath === "/" ? BASE : `${BASE}${routePath}`,
    lastModified: lm(routePath),
    changeFrequency,
    // 0.8 - 0.1 在浮點數下是 0.7000000000000001，會原樣寫進 sitemap.xml。
    // 四捨五入到小數一位，讓輸出維持乾淨的 0.1 級距。
    priority: Math.round(priority * 10) / 10,
  };
}

/** 8 個英檢／日檢級別：總覽頁與家長指南總覽頁都進索引 */
const LANG_LEVELS = [
  "elementary", "intermediate", "upper-intermediate",
  "jlpt-n5", "jlpt-n4", "jlpt-n3", "jlpt-n2", "jlpt-n1",
];

/** unit 頁進索引的級別與單元數（與 lib/unit-seo.ts 的 unitPagesIndexable 同步） */
const INDEXED_UNIT_LEVELS: [string, number][] = [
  ["elementary", 20],
];

/** 6 個科目首頁 */
const SUBJECT_HOMES = ["chinese-lang", "math", "history-geo", "music", "finance", "board-games"];

export default function sitemap(): MetadataRoute.Sitemap {
  return [
    // 平台頁
    entry("/", "monthly", 1),
    entry("/about", "monthly", 0.5),
    entry("/how-to-use", "monthly", 0.6),
    entry("/faq", "monthly", 0.6),
    entry("/exam-info", "monthly", 0.7),
    entry("/parent-guide", "monthly", 0.6),

    // Blog
    entry("/blog", "weekly", 0.7),
    ...getAllSlugs().map(slug => entry(`/blog/${slug}`, "weekly", 0.7)),

    // 級別總覽 + 家長指南總覽
    ...LANG_LEVELS.flatMap(level => [
      entry(`/${level}`, "weekly", level === "elementary" ? 0.9 : 0.8),
      entry(`/${level}/guide`, "monthly", 0.6),
    ]),

    // 已擴寫內容的級別的 unit 頁
    ...INDEXED_UNIT_LEVELS.flatMap(([level, count]) =>
      Array.from({ length: count }, (_, i) => entry(`/${level}/unit/${i + 1}`, "monthly", 0.8)),
    ),

    // 科目首頁
    ...SUBJECT_HOMES.map(s => entry(`/${s}`, "weekly", 0.8)),
  ];
}
